// 真实 Edge 的 Window 全局枚举顺序与 descriptor 形状。
//
// ## 为什么这是数据而不是代码
//
// `Object.getOwnPropertyNames(window)` 的序列在真实 Edge 里是确定的，也是指纹
// 的一维。原来的实现是一份 1.5 万行的生成代码，把这份顺序编译进了「捕获
// descriptor → 全部删除 → 按目标顺序重定义」三段展开的语句里——**而生成它的
// 工具没有进版本库**（文件头写着 `tools/generate-window-surface-order.mjs`，
// 该目录不存在）。代价有两条，都不是风格问题：
//
// 1. 新增一个全局要在三处手改、顺序敏感、没有任何校验；
// 2. **版本门控无法表达**。`FontFaceSet` 只在 `browserMajorVersion >= 151`
//    暴露，因为进不了那份文件，它在 151 profile 下落在索引 61（紧随 V8 内建
//    之后），真实 Edge 是 517——其后 1171 个全局的索引全部偏移 1。
//    实测：`tests/window-surface-order-test.js`。
//
// 顺序变成数据以后，门控是一个字段，新增全局是一行。
//
// ## 再生与校验
//
// `node scripts/build-window-surface-order.mjs`（`--write` 写入）。
// 顺序的权威来源是 `fixtures/fingerprint/edge-globals.json` 的 `globals`
// ——采集时不排序，就是为了保留这份顺序。
//
// **顺序不是「旧顺序 + 追加新增项」**：实测 Edge 151 → 152 有 9 个已有全局挪了
// 位置（`FeaturePolicy` 523 → 69、`PerformanceLongAnimationFrameTiming`
// 333 → 1191、`WebAssembly` / `XSLTProcessor` / `RTCDataChannel` /
// `PageRevealEvent` / `onpagereveal` / `PerformanceScriptTiming` /
// `PerformanceTimingConfidence` 亦然）。换基准必须整表重采。
//
// ## V8 内建前缀刻意不在表里
//
// 真实 Edge 的前 61 项是 V8 自己注册的语言内建，加上 Chromium 紧随其后装的
// `console`。NV8 既不安装也不重排它们：Chromium 与 Node 用同一个引擎，实测这
// 段逐位对齐（`Object` → 0、`console` → 60、`Option` → 61）。清单与断言在
// `scripts/build-window-surface-order.mjs` 的 `V8_BUILTIN_PREFIX`。
//
// ## 版本门控
//
// 第三个元素是可选的门控对象：
//
//   { since: 151 }   →  browserMajorVersion >= 151 才安装
//   { before: 152 }  →  browserMajorVersion <  152 才安装
//   { pending: "理由" } →  真实 Edge 有但 NV8 未实现，任何版本都不安装
//
// 三者可同时给。被门控排除的项**必须在 globalThis 上不存在**——
// `finalizeWindowSurfaceOrder` 会检查，因为多一个真实 Edge 该版本没有的全局
// 是可识别特征，而它同时还会把后续所有全局的索引推偏。
//
// `pending` 是「已登记的缺口」的**单一来源**：`edge-surface-parity-test.js`
// 与 `edge-member-parity-test.js` 都从这张表读，不各自维护名单。两处登记
// 必然漂移，而且位置信息只有这张表有。当前 Edge 152 基准没有 pending 项；
// 未来的缺口必须写明理由，不能静默从表中消失。

